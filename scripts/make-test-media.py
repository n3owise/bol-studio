#!/usr/bin/env python3
"""Create synthetic smoke-test media locally; this is not an accuracy benchmark."""

from __future__ import annotations

import argparse
import json
import math
import re
import shutil
import struct
import subprocess
import wave
from pathlib import Path


NATIVE_REFERENCE = "नमस्ते दोस्तों। आज हम सीखेंगे कि अपनी वीडियो में शानदार captions कैसे बनाएं। बस अपनी video upload करो, और हर word के साथ animation देखो। यह बहुत आसान है।"
ROMAN_REFERENCE = "Namaste doston. Aaj hum seekhenge ki apni video mein shandaar captions kaise banayein. Bas apni video upload karo, aur har word ke saath animation dekho. Yeh bahut aasan hai."
ENGLISH_REFERENCE = "Welcome to the caption studio. Upload your video, edit every word, and make your captions come alive."


def run(*args: str) -> None:
    subprocess.run(args, check=True, stdout=subprocess.DEVNULL)


def tone(path: Path, duration: float = 4.0, amplitude: float = 0.18) -> None:
    """A fixed PCM signal gives FFmpeg a deterministic non-speech fixture."""
    sample_rate = 16_000
    with wave.open(str(path), "wb") as output:
        output.setnchannels(1)
        output.setsampwidth(2)
        output.setframerate(sample_rate)
        output.writeframes(b"".join(struct.pack("<h", int(amplitude * 32767 * math.sin(2 * math.pi * 440 * i / sample_rate))) for i in range(int(sample_rate * duration))))


def main() -> None:
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument("--output", type=Path, default=Path(__file__).resolve().parents[1] / "data" / "test-fixtures")
    args = parser.parse_args()
    output = args.output.resolve()
    output.mkdir(parents=True, exist_ok=True)
    ffmpeg = shutil.which("ffmpeg")
    if not ffmpeg:
        parser.exit(1, "FFmpeg is required to create the integration video fixture.\n")
    tone(output / "tone.wav")
    tone(output / "silence.wav", amplitude=0)
    run(ffmpeg, "-hide_banner", "-loglevel", "error", "-y", "-f", "lavfi", "-i", "testsrc2=size=360x640:rate=30:duration=4", "-i", str(output / "tone.wav"), "-c:v", "libx264", "-preset", "ultrafast", "-pix_fmt", "yuv420p", "-c:a", "aac", "-shortest", "-movflags", "+faststart", str(output / "integration.mp4"))
    manifest = {
        "purpose": "Synthetic integration smoke test only. Not real Hinglish accuracy evaluation.",
        "generated_locally": True,
        "deterministic_fixtures": ["tone.wav", "silence.wav", "integration.mp4"],
        "speech_fixtures": [],
        "notes": "Speech is generated by an installed macOS voice. Pronunciation/timing may change with macOS versions; word times are deliberately not fabricated.",
    }
    say = shutil.which("say")
    if say:
        voices = subprocess.run([say, "-v", "?"], check=True, capture_output=True, text=True).stdout
        hindi_voice = next((re.split(r"\s+hi_IN\s+", line)[0].strip() for line in voices.splitlines() if "hi_IN" in line), None)
        english_voice = next((re.split(r"\s+en_IN\s+", line)[0].strip() for line in voices.splitlines() if "en_IN" in line), None)
        for name, voice, text, roman in [("hinglish", hindi_voice, NATIVE_REFERENCE, ROMAN_REFERENCE), ("english", english_voice, ENGLISH_REFERENCE, ENGLISH_REFERENCE)]:
            if not voice:
                continue
            source = output / f"{name}.aiff"
            try:
                run(say, "-v", voice, "-r", "150", "-o", str(source), text)
                run(ffmpeg, "-hide_banner", "-loglevel", "error", "-y", "-i", str(source), "-ar", "16000", "-ac", "1", str(output / f"{name}.wav"))
                run(ffmpeg, "-hide_banner", "-loglevel", "error", "-y", "-f", "lavfi", "-i", "color=c=0x151a20:s=360x640:r=30", "-i", str(output / f"{name}.wav"), "-c:v", "libx264", "-preset", "ultrafast", "-pix_fmt", "yuv420p", "-c:a", "aac", "-shortest", "-movflags", "+faststart", str(output / f"{name}.mp4"))
                manifest["speech_fixtures"].append({"audio": f"{name}.wav", "video": f"{name}.mp4", "voice": voice, "reference_native": text, "reference_roman": roman, "synthetic": True})
            except subprocess.CalledProcessError as exc:
                manifest.setdefault("speech_generation_errors", []).append({"name": name, "error": str(exc)})
    (output / "manifest.json").write_text(json.dumps(manifest, ensure_ascii=False, indent=2) + "\n")
    print(json.dumps({"directory": str(output), **manifest}, ensure_ascii=False, indent=2))


if __name__ == "__main__":
    main()
